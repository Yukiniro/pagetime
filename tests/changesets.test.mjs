import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, readFileSync, rmSync, symlinkSync, writeFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));

test('actual Changesets CLI aggregates patch/minor, updates changelog and consumes records; empty records do not bump', t => {
  const sourceVersion = JSON.parse(readFileSync(join(root, 'package.json'))).version;
  const directory = mkdtempSync(join(tmpdir(), 'pagetime-changesets-'));
  t.after(() => rmSync(directory, { recursive: true, force: true }));
  const put = (path, value) => { mkdirSync(dirname(join(directory, path)), { recursive: true }); writeFileSync(join(directory, path), value); };
  const run = (...args) => execFileSync(process.execPath, [join(root, 'node_modules/@changesets/cli/bin.js'), ...args], { cwd: directory, encoding: 'utf8' });
  symlinkSync(join(root, 'node_modules'), join(directory, 'node_modules'), process.platform === 'win32' ? 'junction' : 'dir');
  put('package.json', '{"name":"pagetime","version":"1.0.0","private":true}');
  put('.changeset/config.json', readFileSync(join(root, '.changeset/config.json')));
  put('.gitignore', 'node_modules/\n');
  execFileSync('git', ['init', '--quiet', '--initial-branch=main'], { cwd: directory });
  execFileSync('git', ['add', '.'], { cwd: directory });
  execFileSync('git', ['-c', 'user.name=PageTime Test', '-c', 'user.email=test@example.invalid', 'commit', '--quiet', '-m', 'fixture'], { cwd: directory });
  put('.changeset/empty.md', '---\n---\n');
  run('status', '--output=plan.json');
  assert.deepEqual(JSON.parse(readFileSync(join(directory, 'plan.json'))).releases, []);
  put('.changeset/patch.md', '---\n"pagetime": patch\n---\n\nFix saved records\n');
  run('status', '--output=plan.json');
  let plan = JSON.parse(readFileSync(join(directory, 'plan.json')));
  assert.equal(plan.releases[0].newVersion, '1.0.1');
  put('.changeset/minor.md', '---\n"pagetime": minor\n---\n\nAdd a complete feature\n');
  run('status', '--output=plan.json');
  plan = JSON.parse(readFileSync(join(directory, 'plan.json')));
  assert.equal(plan.releases[0].newVersion, '1.1.0');
  run('version');
  assert.equal(JSON.parse(readFileSync(join(directory, 'package.json'))).version, '1.1.0');
  const changelog = readFileSync(join(directory, 'CHANGELOG.md'), 'utf8');
  assert.match(changelog, /## 1\.1\.0/);
  assert.match(changelog, /Fix saved records/);
  assert.match(changelog, /Add a complete feature/);
  assert.equal(existsSync(join(directory, '.changeset/patch.md')), false);
  assert.equal(existsSync(join(directory, '.changeset/minor.md')), false);
  assert.equal(JSON.parse(readFileSync(join(root, 'package.json'))).version, sourceVersion);
});
